#include <stdio.h>

int main() {
    // Declare an integer variable 'a'
    int a = 2;
    
    // Declare a float variable 'b'
    float b = 3.5;
    
    // Declare and initialize multiple variables
    int c = 4, d = 5;
    
    printf("a = %d\n", a);
    printf("b = %.2f\n", b);
    printf("c = %d\n", c);
    printf("d = %d\n", d);
    
    return 0;
}